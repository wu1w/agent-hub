function interpolate(template, vars) {
  if (!vars) return template;
  return String(template).replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? "" : String(vars[k])));
}

export function detectLang() {
  try {
    const stored = localStorage.getItem("hub-lang");
    if (stored === "en" || stored === "zh") return stored;
  } catch {
    // ignore
  }
  const nav = (globalThis.navigator?.language || "").toLowerCase();
  if (nav.startsWith("en")) return "en";
  return "zh";
}

let current = "zh";

export function getLang() {
  return current;
}

export function setLang(lang) {
  current = lang === "en" ? "en" : "zh";
  try {
    localStorage.setItem("hub-lang", current);
  } catch {
    // ignore
  }
  return current;
}

export function t(key, vars) {
  const table = STRINGS[current] || STRINGS.zh;
  const template = table[key] ?? STRINGS.zh[key] ?? key;
  return interpolate(template, vars);
}

export function applyDom(root = document) {
  root.documentElement?.setAttribute?.("lang", t("html.lang"));
  if (root.title !== undefined && root.querySelector?.("title")) {
    const titleEl = root.querySelector("title");
    if (titleEl?.dataset?.i18n) titleEl.textContent = t(titleEl.dataset.i18n);
  }
  root.querySelectorAll?.("[data-i18n]").forEach((el) => {
    if (el.tagName === "TITLE") {
      el.textContent = t(el.dataset.i18n);
      if (root.title !== undefined) root.title = el.textContent;
      return;
    }
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll?.("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder));
  });
  root.querySelectorAll?.("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.dataset.i18nTitle));
  });
  root.querySelectorAll?.("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria));
  });
}

export function apiErrorText(message) {
  return translateError(message, current);
}

const hubI18n = { STRINGS, t, setLang, getLang, detectLang, applyDom, apiErrorText, translateError };
if (typeof globalThis !== "undefined") globalThis.hubI18n = hubI18n;
